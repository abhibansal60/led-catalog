import {
  COPIED_LED_FILENAME,
  Program,
  formatControllerLabel,
  formatFileSize,
  getProgramController,
  getProgramMetadataFilename,
} from "@/lib/catalog";
import { clearDirectoryContents } from "@/lib/clearDirectoryContents";
import { filesMatch } from "@/lib/ledFile";
import { deleteProgram as deleteStoredProgram } from "@/lib/storage";
import { writeFileToHandle } from "@/lib/writeFileToHandle";
import type { useAppState } from "./useAppState";
import type { useFileSystem } from "./useFileSystem";
import type { useImportFlow } from "./useImportFlow";
import type { useProgramForm } from "./useProgramForm";

type Deps = ReturnType<typeof useAppState> &
  ReturnType<typeof useFileSystem> &
  ReturnType<typeof useImportFlow> &
  ReturnType<typeof useProgramForm>;

export function useProgramActions(s: Deps) {
  const {
    ensureDirectoryAccess,
    setFeedback,
    programs,
    setPrograms,
    directoryHandle,
    directoryPermission,
    setCopyStatuses,
  } = s;

  const handleDownload = async (program: Program) => {
    if (program.isFileMissing) {
      window.alert(
        "LED file not linked yet. Edit the program to attach a LED file.\nLED फाइल अभी लिंक नहीं है। पहले एडिट करके जोड़ें।"
      );
      return;
    }
    try {
      const directory = await ensureDirectoryAccess();
      if (!directory) {
        return;
      }
      const fileHandle = await directory.getFileHandle(program.storedFileName, { create: false });
      const file = await fileHandle.getFile();
      const arrayBuffer = await file.arrayBuffer();
      const blob = new Blob([arrayBuffer], { type: "application/octet-stream" });
      const url = window.URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = url;
      link.download = COPIED_LED_FILENAME;
      link.type = "application/octet-stream";
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      window.URL.revokeObjectURL(url);
      window.alert("File downloaded! Copy it to SD card.\nफाइल डाउनलोड हो गई! इसे SD कार्ड में कॉपी करें।");
      console.log("⬇️ Program downloaded", {
        id: program.id,
        originalName: program.originalLedName,
      });
    } catch (error) {
      console.error("❌ Download failed", error);
      setFeedback({
        type: "error",
        message: "Download failed. डाउनलोड नहीं हो पाया.",
      });
    }
  };

  const handleDelete = async (id: string) => {
    const confirmed = window.confirm("Delete this program?\nक्या यह प्रोग्राम हटाना है?");
    if (!confirmed) {
      return;
    }

    const programToDelete = programs.find((program) => program.id === id);
    if (!programToDelete) {
      return;
    }

    try {
      await deleteStoredProgram(id);
      setPrograms((prev) => prev.filter((program) => program.id !== id));
      if (directoryHandle && directoryPermission === "granted") {
        try {
          await directoryHandle.removeEntry(programToDelete.storedFileName);
        } catch (fileError) {
          console.warn("⚠️ Could not remove stored LED file", fileError);
        }
      }
      setFeedback({
        type: "success",
        message: "Program deleted. प्रोग्राम हटाया गया.",
      });
      console.log("🗑️ Program deleted", { id });
    } catch (error) {
      console.error("❌ Delete failed", error);
      setFeedback({
        type: "error",
        message: "Could not delete. हटाया नहीं जा सका.",
      });
    }
  };

  const buildProgramMetadataNote = (program: Program): string => {
    const header = [
      "LED Program Metadata",
      "====================",
      "",
    ].join("\n");

    const date = new Date(program.dateAdded);
    const localizedDate = Number.isNaN(date.getTime())
      ? program.dateAdded
      : `${date.toLocaleDateString()} ${date.toLocaleTimeString()}`;

    const controllerLabel = formatControllerLabel(getProgramController(program));
    const metadataFileName = getProgramMetadataFilename(program);

    const lines = [
      header,
      `Program Name: ${program.name || "Not provided"}`,
      `Original LED File: ${program.originalLedName}`,
      `Copied As: ${COPIED_LED_FILENAME}`,
      `Description: ${program.description ? program.description : "(none)"}`,
      `Date Added: ${localizedDate}`,
      `Controller: ${controllerLabel}`,
      `Metadata File: ${metadataFileName}`,
    ];

    if (program.fileSizeBytes !== undefined && program.fileSizeBytes !== null) {
      lines.push(`File Size: ${formatFileSize(program.fileSizeBytes)}`);
    }

    lines.push("", "This note is auto-generated by the LED Catalog app.");

    return lines.join("\n");
  };

  const handleCopyToSdCard = async (program: Program) => {
    if (!("showDirectoryPicker" in window)) {
      window.alert("Browser does not support direct SD card access.\nकृपया Chrome या Edge का इस्तेमाल करें।");
      return;
    }

    if (program.isFileMissing) {
      window.alert(
        "LED file not linked yet. Edit the program to attach a LED file before copying.\nLED फाइल अभी लिंक नहीं है। पहले एडिट करके जोड़ें।"
      );
      return;
    }

    let writable: FileSystemWritableFileStream | null = null;
    let metadataWritable: FileSystemWritableFileStream | null = null;

    try {
      const sourceDirectory = await ensureDirectoryAccess();
      if (!sourceDirectory) {
        return;
      }

      const sourceFileHandle = await sourceDirectory.getFileHandle(program.storedFileName, { create: false });
      const sourceFile = await sourceFileHandle.getFile();

      const sdHandle = await window.showDirectoryPicker({ mode: "readwrite" });

      const confirmedFormat = window.confirm(
        "This will DELETE everything currently on the SD card before copying the new program. Continue?\n"
          + "यह SD कार्ड की सभी मौजूदा फाइलें मिटा देगा, फिर नया प्रोग्राम कॉपी होगा। जारी रखें?"
      );
      if (!confirmedFormat) {
        console.log("⚠️ SD card copy cancelled — user declined format");
        return;
      }

      setCopyStatuses((prev) => ({
        ...prev,
        [program.id]: { status: "copying", progress: 0 },
      }));

      await clearDirectoryContents(sdHandle);

      const targetFileHandle = await sdHandle.getFileHandle(COPIED_LED_FILENAME, { create: true });

      await writeFileToHandle(targetFileHandle, sourceFile, (ratio) => {
        setCopyStatuses((prev) => ({
          ...prev,
          [program.id]: { status: "copying", progress: Math.round(ratio * 100) },
        }));
      });

      setCopyStatuses((prev) => ({
        ...prev,
        [program.id]: { status: "verifying", progress: 100 },
      }));

      const copiedFile = await targetFileHandle.getFile();
      const matches = await filesMatch(sourceFile, copiedFile);
      if (!matches) {
        console.error("❌ SD card copy verification failed", {
          id: program.id,
          sourceBytes: sourceFile.size,
          copiedBytes: copiedFile.size,
        });
        setCopyStatuses((prev) => ({
          ...prev,
          [program.id]: {
            status: "error",
            progress: 100,
            message: `Copied but didn't verify (source ${sourceFile.size} bytes, SD card ${copiedFile.size} bytes). SD card may be failing — try a different card.`,
          },
        }));
        window.alert(
          "File copied but does not match the original — the SD card may be corrupted or failing. Try again or use a different card.\n"
            + "फाइल कॉपी हुई पर मूल फाइल से मेल नहीं खाती — SD कार्ड खराब हो सकता है। दोबारा कोशिश करें या दूसरा कार्ड इस्तेमाल करें।"
        );
        window.setTimeout(() => {
          setCopyStatuses((prev) => {
            const entry = prev[program.id];
            if (!entry || entry.status === "copying" || entry.status === "verifying") {
              return prev;
            }
            const { [program.id]: _removed, ...rest } = prev;
            return rest;
          });
        }, 8000);
        return;
      }

      const metadataFileName = getProgramMetadataFilename(program);

      try {
        const metadataContent = buildProgramMetadataNote(program);
        const metadataHandle = await sdHandle.getFileHandle(metadataFileName, { create: true });
        metadataWritable = await metadataHandle.createWritable();
        await metadataWritable.write(metadataContent);
        await metadataWritable.close();
        metadataWritable = null;
      } catch (metadataError) {
        console.error("⚠️ Could not write metadata note to SD card", metadataError);
        if (metadataWritable) {
          try {
            await metadataWritable.abort();
          } catch (abortMetadataError) {
            console.warn("⚠️ Could not abort metadata write stream", abortMetadataError);
          }
        }
        setCopyStatuses((prev) => ({
          ...prev,
          [program.id]: { status: "error", progress: 100 },
        }));
        window.alert(
          "LED file copied but metadata note could not be saved.\nLED फाइल कॉपी हो गई पर नोट सेव नहीं हो पाया।"
        );

        window.setTimeout(() => {
          setCopyStatuses((prev) => {
            const entry = prev[program.id];
            if (!entry || entry.status === "copying") {
              return prev;
            }
            const { [program.id]: _removed, ...rest } = prev;
            return rest;
          });
        }, 5000);
        return;
      }

      setCopyStatuses((prev) => ({
        ...prev,
        [program.id]: { status: "success", progress: 100 },
      }));
      window.alert(
        `Copied and verified as ${COPIED_LED_FILENAME} with details in ${metadataFileName}.\n`
          + `SD कार्ड में ${COPIED_LED_FILENAME} कॉपी हुआ और जांचा गया, नोट ${metadataFileName} में सेव हुआ।`
      );
      console.log("💾 Program copied to SD card", {
        id: program.id,
        directory: sdHandle.name,
        metadataFile: metadataFileName,
      });

      window.setTimeout(() => {
        setCopyStatuses((prev) => {
          const entry = prev[program.id];
          if (!entry || entry.status === "copying") {
            return prev;
          }
          const { [program.id]: _removed, ...rest } = prev;
          return rest;
        });
      }, 4000);
    } catch (error) {
      if (error instanceof DOMException && error.name === "AbortError") {
        console.log("⚠️ SD card copy cancelled before selecting card");
        return;
      }
      console.error("❌ Copy to SD card failed", error);
      if (writable) {
        try {
          await writable.abort();
        } catch (abortError) {
          console.warn("⚠️ Could not abort write stream", abortError);
        }
      }
      if (metadataWritable) {
        try {
          await metadataWritable.abort();
        } catch (abortMetadataError) {
          console.warn("⚠️ Could not abort metadata write stream", abortMetadataError);
        }
      }
      setCopyStatuses((prev) => ({
        ...prev,
        [program.id]: { status: "error", progress: 0 },
      }));
      window.alert("Could not copy to SD card. SD कार्ड में कॉपी नहीं हो पाया।");

      window.setTimeout(() => {
        setCopyStatuses((prev) => {
          const entry = prev[program.id];
          if (!entry || entry.status === "copying") {
            return prev;
          }
          const { [program.id]: _removed, ...rest } = prev;
          return rest;
        });
      }, 5000);
    }
  };

  const handleVerifySdCard = async (program: Program) => {
    if (!("showDirectoryPicker" in window)) {
      window.alert("Browser does not support direct SD card access.\nकृपया Chrome या Edge का इस्तेमाल करें।");
      return;
    }
    if (program.isFileMissing) {
      window.alert(
        "LED file not linked yet. Edit the program to attach a LED file first.\nLED फाइल अभी लिंक नहीं है। पहले एडिट करके जोड़ें।"
      );
      return;
    }

    try {
      const sourceDirectory = await ensureDirectoryAccess();
      if (!sourceDirectory) {
        return;
      }
      const sourceFileHandle = await sourceDirectory.getFileHandle(program.storedFileName, { create: false });
      const sourceFile = await sourceFileHandle.getFile();

      const sdHandle = await window.showDirectoryPicker({ mode: "read" });
      let sdFileHandle: FileSystemFileHandle;
      try {
        sdFileHandle = await sdHandle.getFileHandle(COPIED_LED_FILENAME, { create: false });
      } catch (error) {
        window.alert(
          `No ${COPIED_LED_FILENAME} found on that SD card.\nउस SD कार्ड में ${COPIED_LED_FILENAME} नहीं मिली।`
        );
        return;
      }
      const sdFile = await sdFileHandle.getFile();

      const matches = await filesMatch(sourceFile, sdFile);
      if (matches) {
        window.alert(
          `✅ SD card matches the catalog copy exactly (${formatFileSize(sdFile.size)}). Safe to install.\n`
            + `SD कार्ड बिल्कुल कैटलॉग जैसा है। लगाना सुरक्षित है।`
        );
      } else {
        window.alert(
          `❌ SD card file does NOT match (catalog ${formatFileSize(sourceFile.size)}, SD card ${formatFileSize(sdFile.size)}). Re-copy before installing.\n`
            + `SD कार्ड की फाइल मेल नहीं खाती। दोबारा कॉपी करें, फिर लगाएं।`
        );
      }
      console.log("🔍 SD card verified", {
        id: program.id,
        matches,
        sourceBytes: sourceFile.size,
        sdBytes: sdFile.size,
      });
    } catch (error) {
      if (error instanceof DOMException && error.name === "AbortError") {
        return;
      }
      console.error("❌ SD card verification failed", error);
      window.alert("Could not verify SD card. जांच नहीं हो पाई।");
    }
  };

  return {
    handleDownload,
    handleDelete,
    buildProgramMetadataNote,
    handleCopyToSdCard,
    handleVerifySdCard,
  };
}
